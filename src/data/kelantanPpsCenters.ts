function getCenterType(name: string): 'Sekolah' | 'Masjid' | 'Dewan' | 'Madrasah' | 'Balai Raya' | 'Lain-lain' {
    const upper = name.toUpperCase();
    if (upper.includes('SEK') || upper.includes('S.K') || upper.includes('SK') || upper.includes('S.M.K') || upper.includes('SMK') || upper.includes('SJK') || upper.includes('SRJK') || upper.includes('SMA') || upper.includes('SMU') || upper.includes('MAKTAB') || upper.includes('TADIKA') || upper.includes('TABIKA') || upper.includes('KOLEJ') || upper.includes('MRSM')) return 'Sekolah';
    if (upper.includes('MASJID') || upper.includes('SURAU')) return 'Masjid';
    if (upper.includes('DEWAN') || upper.includes('KOMPLEKS') || upper.includes('STESEN') || upper.includes('STADIUM') || upper.includes('PUSAT')) return 'Dewan';
    if (upper.includes('MADRASAH') || upper.includes('BALAISAH') || upper.includes('PONDOK') || upper.includes('MAAHAD')) return 'Madrasah';
    if (upper.includes('BALAI') || upper.includes('BALAIRAYA') || upper.includes('KRT') || upper.includes('PEJABAT') || upper.includes('POS')) return 'Balai Raya';
    return 'Lain-lain';
}

function getEstimatedCapacity(type: string): number {
    if (type === 'Dewan') return 600;
    if (type === 'Sekolah') return 450;
    if (type === 'Masjid') return 500;
    if (type === 'Balai Raya') return 250;
    return 200;
}

